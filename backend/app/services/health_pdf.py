"""A readable PDF health summary of the user's own records (frontend_spec.md Section 16.1).

Built by fixed rules from existing records, with no AI. Values read from documents are shown as read, with
their date and source; nothing missing is filled in.
"""

import uuid
from datetime import UTC, datetime

from fpdf import FPDF
from sqlalchemy import select
from sqlalchemy.orm import Session

from app.models.auth import User
from app.models.document import Document
from app.models.prescription import FollowUp
from app.services.profile_service import ProfileService
from app.services.timeline_service import TimelineService
from app.services.vitals_service import VitalsService

TYPE_LABELS = {
    "lab_report": "Laboratory reports",
    "prescription": "Prescription",
    "discharge_summary": "Discharge summary",
    "consultation_note": "Consultation note",
    "imaging_report": "Text-based imaging reports",
    "pathology_report": "Pathology reports",
    "specialist_report": "Specialist reports",
    "other": "Other",
    "unknown": "Type not set",
}
BMI_LABELS = {
    "underweight": "Underweight",
    "healthy": "Healthy weight",
    "overweight": "Overweight",
    "obesity_1": "Obesity (class 1)",
    "obesity_2": "Obesity (class 2)",
    "obesity_3": "Obesity (class 3, severe)",
}
NOT_MENTIONED = "Not mentioned"
MAX_VITALS = 10
INK = (31, 31, 31)
MUTED = (92, 92, 92)
ACCENT = (29, 95, 174)

# The built-in PDF fonts cover Latin-1 only: common symbols are spelled out, anything else becomes "?".
_REPLACEMENTS = {
    "→": "->",
    "–": "-",
    "—": "-",
    "≥": ">=",
    "≤": "<=",
    "‘": "'",
    "’": "'",
    "“": '"',
    "”": '"',
    "•": "-",
    "…": "...",
    " ": " ",
}


def _text(value: object) -> str:
    text = str(value)
    for symbol, plain in _REPLACEMENTS.items():
        text = text.replace(symbol, plain)
    return text.encode("latin-1", "replace").decode("latin-1")


def _day(value) -> str:
    return value.strftime("%d-%b-%Y") if value else NOT_MENTIONED


class _Pdf(FPDF):
    def __init__(self, generated: str) -> None:
        super().__init__(format="A4")
        self.generated = generated
        self.set_margins(18, 18, 18)
        self.set_auto_page_break(auto=True, margin=22)

    def footer(self) -> None:
        self.set_y(-16)
        self.set_font("Helvetica", size=7.5)
        self.set_text_color(*MUTED)
        self.multi_cell(
            0,
            3.6,
            _text(
                f"Generated by Healthfolio on {self.generated}. From your own records; values read from "
                f"documents may contain reading errors - check the originals. Not medical advice. "
                f"Page {self.page_no()}/{{nb}}"
            ),
            align="C",
        )


class HealthPdf:
    def __init__(self, session: Session) -> None:
        self.session = session

    def build(self, user: User) -> bytes:
        generated = datetime.now(UTC).strftime("%d-%b-%Y %H:%M UTC")
        pdf = _Pdf(generated)
        self.pdf = pdf
        pdf.add_page()
        pdf.set_font("Helvetica", "B", 20)
        pdf.set_text_color(*ACCENT)
        pdf.cell(0, 10, "Health Summary", new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", size=9.5)
        pdf.set_text_color(*MUTED)
        pdf.multi_cell(0, 5, _text(f"Prepared for {user.email} on {generated}."), new_x="LMARGIN", new_y="NEXT")
        pdf.ln(2)

        profile = ProfileService(self.session).profile(user.id)
        self._personal(profile)
        self._list("Allergies", [self._allergy(a) for a in profile["allergies"]], empty="No allergies recorded.")
        self._list(
            "Conditions",
            [f"{c.name} ({c.status})" for c in profile["conditions"]],
            empty="No conditions in your Health Profile.",
        )
        self._list(
            "Current medicines (marked as taking)",
            [self._medicine(m) for m in profile["active_medications"]],
            empty="No medicines marked as taking.",
        )
        self._follow_ups(user.id)
        self._results(user.id)
        self._vitals(user.id)
        self._history(profile)
        self._documents(user.id)
        return bytes(pdf.output())

    # ---------- layout helpers ----------

    def _heading(self, title: str) -> None:
        pdf = self.pdf
        pdf.ln(3)
        pdf.set_font("Helvetica", "B", 12.5)
        pdf.set_text_color(*ACCENT)
        pdf.cell(0, 7, _text(title), new_x="LMARGIN", new_y="NEXT")
        pdf.set_draw_color(*ACCENT)
        pdf.line(pdf.l_margin, pdf.get_y(), pdf.w - pdf.r_margin, pdf.get_y())
        pdf.ln(1.5)
        pdf.set_text_color(*INK)

    def _line(self, text: str, *, muted: bool = False, bold: bool = False) -> None:
        pdf = self.pdf
        pdf.set_font("Helvetica", "B" if bold else "", 10)
        pdf.set_text_color(*(MUTED if muted else INK))
        pdf.multi_cell(0, 5.2, _text(text), new_x="LMARGIN", new_y="NEXT")

    def _list(self, title: str, items: list[str], *, empty: str) -> None:
        self._heading(title)
        if not items:
            self._line(empty, muted=True)
        for item in items:
            self._line(f"- {item}")

    # ---------- sections ----------

    def _personal(self, profile: dict) -> None:
        self._heading("Personal data")
        values = profile["values"]

        def show(field: str, unit: str = "") -> str:
            value = values.get(field)
            return f"{value.value}{unit}" if value else NOT_MENTIONED

        bmi = profile["bmi"]
        bmi_text = NOT_MENTIONED
        if bmi is not None:
            category = BMI_LABELS.get(profile["bmi_category"] or "", "no adult category")
            bmi_text = f"{bmi} ({category})"
        for label, value in (
            ("Date of birth", show("date_of_birth")),
            ("Sex", show("sex")),
            ("Blood group", show("blood_group")),
            ("Height", show("height", " cm")),
            ("Weight", show("weight", " kg")),
            ("BMI", bmi_text),
        ):
            self._line(f"{label}: {value}")

    @staticmethod
    def _medicine(medicine) -> str:
        name = " ".join(part for part in (medicine.name, medicine.strength) if part)
        return f"{name} - {medicine.dosage_text or 'how to take not mentioned'}"

    @staticmethod
    def _allergy(allergy) -> str:
        parts = [allergy.value]
        if allergy.category:
            parts.append(f"({allergy.category})")
        if allergy.detail:
            parts.append(f"- reaction: {allergy.detail}")
        return " ".join(parts)

    def _follow_ups(self, user_id: uuid.UUID) -> None:
        today = datetime.now(UTC).date()
        scheduled = self.session.scalars(
            select(FollowUp)
            .where(FollowUp.user_id == user_id, FollowUp.status == "scheduled")
            .order_by(FollowUp.due_date)
        ).all()
        self._list(
            "Checkups and follow-ups",
            [f"{_day(f.due_date)}: {f.title}{' (overdue)' if f.due_date < today else ''}" for f in scheduled],
            empty="No scheduled follow-ups.",
        )

    def _results(self, user_id: uuid.UUID) -> None:
        self._heading("Results outside the range printed on their report")
        entries = [e for e in TimelineService(self.session).entries(user_id) if e.category == "lab_results"]
        shown = False
        for entry in entries:
            outside = [line for line in entry.lines if "(high;" in line or "(low;" in line]
            if not outside:
                continue
            shown = True
            self._line(f"{_day(entry.date)} - {entry.source_document_title or 'Document'}", bold=True)
            for line in outside:
                self._line(f"   {line}")
        if not shown:
            self._line(
                "None found. This is not a health check: results without a printed range are not compared.", muted=True
            )
        else:
            self._line("For review with your doctor; ranges differ between laboratories.", muted=True)

    def _vitals(self, user_id: uuid.UUID) -> None:
        readings = VitalsService(self.session).readings(user_id)[:MAX_VITALS]
        items = []
        for r in readings:
            parts = []
            if r.systolic is not None:
                parts.append(f"BP {r.systolic}/{r.diastolic} mmHg")
            if r.heart_rate is not None:
                parts.append(f"heart rate {r.heart_rate} bpm")
            items.append(f"{_day(r.measured_on)}: {', '.join(parts)}" + (f" ({r.context})" if r.context else ""))
        self._list(f"Vital signs (latest {MAX_VITALS})", items, empty="No readings recorded.")

    def _history(self, profile: dict) -> None:
        stays = [
            f"{s['facility_name'] or 'Hospital not mentioned'}: {_day(s['admitted_on'])} to {_day(s['discharged_on'])}"
            + (f" - {'; '.join(s['diagnoses'])}" if s["diagnoses"] else "")
            for s in profile["document_stays"]
        ]
        stays += [f"{i.name} ({_day(i.occurred_on)})" for i in profile["hospitalizations"]]
        self._list("Hospital stays", stays, empty="None recorded.")
        self._list(
            "Past surgeries",
            [f"{i.name} ({_day(i.occurred_on)})" for i in profile["surgeries"]],
            empty="None recorded.",
        )
        self._list(
            "Family medical history",
            [f"{i.relation}: {i.name}" for i in profile["family_history"]],
            empty="None recorded.",
        )

    def _documents(self, user_id: uuid.UUID) -> None:
        documents = self.session.scalars(
            select(Document)
            .where(Document.user_id == user_id, Document.deleted_at.is_(None))
            .order_by(Document.document_date.desc().nulls_last(), Document.created_at.desc())
        ).all()
        self._list(
            "Your documents",
            [
                f"{_day(d.document_date)} - {d.title} ({TYPE_LABELS.get(d.category, d.category)}"
                f"{', ' + d.provider_name if d.provider_name else ''})"
                for d in documents
            ],
            empty="No documents uploaded.",
        )
